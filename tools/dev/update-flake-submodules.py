#!/usr/bin/env python3
"""Regenerates the git submodule inputs of flake.nix from the submodules checked out in this repository.

The Nix package can't use `inputs.self.submodules` because quickjs pins test262 as a nested submodule (huge and not
needed to build), so each top-level submodule is pinned as a non-flake input named `submodule-<directory>` instead.

Run this after bumping any submodule, then commit flake.nix and flake.lock:

    tools/dev/update-flake-submodules.py
"""
import re
import subprocess
import sys
from pathlib import Path

BEGIN = "    # BEGIN SUBMODULES (generated by tools/dev/update-flake-submodules.py, do not edit)\n"
END = "    # END SUBMODULES\n"

root = Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip())
flake = root / "flake.nix"


def git(*args: str) -> str:
    return subprocess.check_output(["git", "-C", str(root), *args], text=True)


entries = []
for line in git("submodule", "status").splitlines():
    rev, path = line[1:].split()[:2]
    url = git("config", "-f", ".gitmodules", f"submodule.{path}.url").strip()
    match = re.match(r"https://github\.com/([^/]+)/([^/]+?)(\.git)?$", url)

    if not path.startswith("src/External/") or match is None:
        sys.exit(f"unsupported submodule {path} ({url})")

    owner, repo = match.group(1), match.group(2)
    name = path.removeprefix("src/External/")
    entries.append(
        f'    submodule-{name} = {{\n'
        f'      url = "github:{owner}/{repo}/{rev}";\n'
        f"      flake = false;\n"
        f"    }};\n"
    )

content = flake.read_text()
start, end = content.index(BEGIN), content.index(END)
flake.write_text(content[: start + len(BEGIN)] + "".join(entries) + content[end:])

subprocess.check_call(["nix", "flake", "lock"], cwd=root)
print(f"updated {len(entries)} submodule inputs")
